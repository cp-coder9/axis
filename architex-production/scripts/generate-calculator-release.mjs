import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = resolve(root, 'config/calculator-release-manifest.json');
const tsPath = resolve(root, 'lib/generated/calculator-release.ts');
const phpPath = resolve(root, 'backend/generated/calculator_release.php');
const expectedIds = [
  'steel-beam', 'concrete-beam', 'timber-beam', 'geo-bearing', 'wind-load',
  'stormwater-rational', 'duct-sizing', 'heat-gain', 'travel-distance',
  'fire-resistance', 'fire-water', 'cable-sizing', 'max-demand', 'cold-water',
  'drainage-fu', 'geyser-sizing', 'unit-converter',
];

function fail(message) {
  throw new Error(`Invalid calculator release manifest: ${message}`);
}

async function validate(manifest) {
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.calculators)) fail('expected schemaVersion 1 and calculators array');
  const ids = manifest.calculators.map((entry) => entry.id);
  if (JSON.stringify(ids) !== JSON.stringify(expectedIds)) fail('calculator IDs must be unique and in canonical registry order');
  for (const entry of manifest.calculators) {
    if (!['contained', 'validated'].includes(entry.releaseState)) fail(`${entry.id} has an unknown release state`);
    if (typeof entry.recordable !== 'boolean' || typeof entry.message !== 'string' || entry.message.length === 0) fail(`${entry.id} has invalid policy fields`);
    if (!Number.isInteger(entry.minimumGoldenCases) || entry.minimumGoldenCases < 1) fail(`${entry.id} has an invalid golden-case minimum`);
    if (!Array.isArray(entry.approvalEvidenceIds) || typeof entry.professionalOwner !== 'string') fail(`${entry.id} has invalid approval metadata`);
    if (entry.releaseState === 'contained' && entry.recordable) fail(`${entry.id} cannot be recordable while contained`);
    if (entry.releaseState === 'validated' && (!entry.recordable || !entry.formulaVersion || entry.approvalEvidenceIds.length === 0)) fail(`${entry.id} requires recordable state, formula version, and approval evidence when validated`);
    if (entry.releaseState === 'validated') {
      const fixturePath = resolve(root, 'test', 'fixtures', 'calculations', `${entry.id}.json`);
      let fixture;
      try {
        fixture = JSON.parse(await readFile(fixturePath, 'utf8'));
      } catch (error) {
        fail(`${entry.id} requires a readable JSON fixture file when validated (${error instanceof Error ? error.message : 'unknown error'})`);
      }
      const cases = Array.isArray(fixture) ? fixture : fixture?.cases;
      if (!Array.isArray(cases) || cases.length < entry.minimumGoldenCases) {
        fail(`${entry.id} requires at least ${entry.minimumGoldenCases} fixture cases when validated`);
      }
      if (cases.some((testCase) => testCase?.formulaVersion !== entry.formulaVersion)) {
        fail(`${entry.id} fixture formula versions must match ${entry.formulaVersion}`);
      }
    }
  }
  const minimum = manifest.calculators.reduce((sum, entry) => sum + entry.minimumGoldenCases, 0);
  if (minimum !== 57) fail(`golden-case minimum must total 57, received ${minimum}`);
}

function generateTs(manifest) {
  return `// Generated by scripts/generate-calculator-release.mjs. Do not edit.\n\nexport type CalculatorReleaseState = 'contained' | 'validated';\n\nexport interface CalculatorRelease {\n  id: string;\n  releaseState: CalculatorReleaseState;\n  recordable: boolean;\n  message: string;\n  formulaVersion: string | null;\n  professionalOwner: string;\n  minimumGoldenCases: number;\n  approvalEvidenceIds: readonly string[];\n}\n\nexport const CALCULATOR_RELEASE_POLICY = ${JSON.stringify(manifest.calculators, null, 2)} as const satisfies readonly CalculatorRelease[];\n`;
}

function phpValue(value, indent = '') {
  if (Array.isArray(value)) return `[${value.map((item) => phpValue(item, indent)).join(', ')}]`;
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function generatePhp(manifest) {
  const rows = manifest.calculators.map((entry) => {
    const fields = Object.entries(entry).map(([key, value]) => `        '${key}' => ${phpValue(value)}`).join(",\n");
    return `    '${entry.id}' => [\n${fields}\n    ]`;
  }).join(",\n");
  return `<?php\n// Generated by scripts/generate-calculator-release.mjs. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn [\n${rows}\n];\n`;
}

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
await validate(manifest);
const outputs = [[tsPath, generateTs(manifest)], [phpPath, generatePhp(manifest)]];
const check = process.argv.includes('--check');
for (const [path, expected] of outputs) {
  if (check) {
    let actual = '';
    try { actual = await readFile(path, 'utf8'); } catch {}
    if (actual !== expected) throw new Error(`Generated artifact is stale: ${path}`);
  } else {
    await writeFile(path, expected, 'utf8');
  }
}
console.log(check ? 'Calculator release artifacts are current.' : 'Generated calculator release artifacts.');
